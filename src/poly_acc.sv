                end
                // sr_i = !rdone;
            end
            if ((is_decode_q       && encode_o_valid) ||
                (is_fn_decompress_q && encode_o_valid) || 
                (is_cbd_q          && cbd_o_valid   ) ||
                (is_rej_samp_q     && cbd_o_valid   ))
            begin
                if (is_cbd_q || is_rej_samp_q) begin
                    upoly_cbd = 1;
                end
                else begin
                    upoly_encode = 1;
                end
                if (ctr1 == n_m1) begin
                    ctr1_rst = 1;
                    ctr0_rst = 1;
                    ctr2_rst = 1;
                    rej_samp_ip_clr = 1;
                    next_state = ST_POLY_OUT;
