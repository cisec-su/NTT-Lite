    chknorm_set = 0;
    chkl1norm_rcv_bu = 0;

    poly_in_frwrd_A = 0;
    poly_in_frwrd_B = 0;
    twiddle_frwrd = 0;

    io_limit = n_m1;

    en_z = 0;

    ntt_ren = 0;

    rej_samp = 1'b0;
    rej_samp_center = rhs_const;
    rej_samp_ip_set = 0;
    rej_samp_ip_clr = 0;

