            if (i_valid) begin
                wzeta = 1;
                if (ctr0 == n_m1) begin
                    next_state = ST_IDLE;
                    done_set = 1;
                    ctr0_rst = 1;
                    ctr3_rst = 1;
                end
                else begin
                    ctr0_inc = 1;
                    ctr3_inc = 1;
                end
            end
        end
        ST_TWIDDLE_FORWARD_PWM: begin
            i_ready = 1;
            if (i_valid) begin
                wpsi = 1;

                if (ctr0 == n_m1) begin
                    next_state = ST_PWM1;
                    ctr0_rst = 1;
                end
                else
                    ctr0_inc = 1;
            end
            twiddle_frwrd = 1;
