always @(posedge clk) begin
    if (rst)
        ctr1 <= 0;
    else if (ctr1_rst || ctr_all_rst)
        ctr1 <= 0;
    else if (ctr1_inc)
        ctr1 <= ctr1 + 1;
end

always @(posedge clk) begin
    if (rst)
        ctr2 <= 0;
    else if (ctr2_rst || ctr_all_rst)
        ctr2 <= 0;
    else if (ctr2_inc)
        ctr2 <= ctr2_p1;
end

always @(posedge clk) begin
    if (rst)
        ctr3 <= 0;
    else if (ctr3_rst || ctr_all_rst)
        ctr3 <= 0;
    else if (ctr3_inc)
        ctr3 <= ctr3 + 1;
end

always @(posedge clk) begin
    ctr0_d <= ctr0;
end

always @(posedge clk) begin
    if (rst)
        state <= ST_IDLE;
    else
        state <= next_state;
end

always @(posedge clk) begin
    if (rst)
        {done, done_int} <= 0;
    else if (done_set)
        {done, done_int} <= 2'b01;
    else if (done_int)
        {done, done_int} <= 2'b10;
    else if (done)
        {done, done_int} <= 2'b00;
end


always @(posedge clk) begin
    if (rst)
        error <= 0;
    else if (error_set)
        error <= 1;
    else if (error)
        error <= 0;
end


always @(posedge clk) begin
    if (rst)
        twiddle_out_q <= 0;
    else if (twiddle_out_set)
        twiddle_out_q <= 1;
    else if (twiddle_out_q)
        twiddle_out_q <= 0;
end


