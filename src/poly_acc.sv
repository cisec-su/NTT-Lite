            pwm_rcv_bu = 1;
        end
        ST_POLY_PWM3: begin
            en_z = 1'b1;
            pwm_zeta_idx = 1;
            if (bu_o_valid && ctr0 == n_m1) begin
                next_state = ST_POLY_OUT;
            end
            pwm_rcv_bu = 1;
        end
        ST_PWM0: begin
            p_ren = 1;
            // TODO: enable below based on op
            twiddle_ram_ren = 1;            
            twiddle_poly_idx = 1;
            //
            if (pwop_i_ready) begin
                bu_i_valid = 1;
                if (ctr1 == pwop_i_limit) begin
                    ctr1_rst = 1;
                    next_state = ST_PWM1;
                end
                else begin
                    ctr1_inc = 1;
                end
            end
            pwm_rcv_bu = 1;
            upoly_zetamul = (is_poly_mode_q & bu_o_valid);
        end
        ST_PWM1: begin
            if (pwop_o_valid && ctr0 == n_m1) begin
                if (is_chk_infnorm_q) begin
                    ctr_all_rst = 1;
                    done_set   = 1;
                    next_state = ST_IDLE;
                end
                else if (is_poly_mode_q && (is_pwm_q || is_mac_q)) begin
                    next_state = ST_POLY_PWM2;
                    ctr0_rst = 1;
                end
                else begin
                    next_state = ST_POLY_OUT;
                end
            end
            pwm_rcv_bu = 1;
            upoly_zetamul = (is_poly_mode_q & bu_o_valid);
        end
        ST_NTT0: begin
            twiddle_ram_ren = (is_sum) ? 0 : 1;
            ntt_ren = 1;
            bu_i_valid = 1;
            if (ctr1 == logn_m1_shft_m1_ctr2) begin
                ctr1_rst = 1;
                next_state = ST_NTT1;
            end
            else begin
                ctr1_inc = 1;
            end
            ntt_rcv_bu = 1;
        end
        ST_NTT1: begin
            // BU input for next stage is valid after processing half of the poly
            // n_over4 (not minus 1) because the write for odd output is delayed
            if ((ctr0_q >= (ntt_limit)) && (ctr2 != logn_m1) && ntt_o_valid_q) begin
                next_state = ST_NTT0;
                ctr2_inc = 1; // go to next stage
            end
            else if (ctr0_q == logn_m1_shft_m1_ctr2 && ntt_o_valid_q) begin
                next_state = (is_sum) ? ST_POLY_OUT : ST_NTT2;
            end
            ntt_rcv_bu = 1;
        end
        ST_NTT2: begin
            ntt_rcv_bu = 1;
            next_state = ST_POLY_OUT;
        end
        ST_POLY_OUT: begin
            p_ren = 1;
            if (!o_dis) begin
                ctr1_inc = 1;
                o_valid = (O_VALID_EARLY) ? 1 : 0;
                next_state = ST_POLY_OUT1;
            end
            else begin
                next_state = ST_IDLE;
                ctr_all_rst = 1;
                done_set = 1;
            end
        end
        ST_POLY_OUT1: begin
            p_ren = o_read;
            o_valid = 1;
            zeropoly = clr_poly_q;
            zerotwiddle = clr_twiddle_q;    
            if (o_read) begin
                if (ctr3 == n_m1 || ((is_encode_q) && (ctr0_p1 == ctr1)) || (is_sum_q)) begin
                    next_state = ST_IDLE;
                    ctr_all_rst = 1;
                    done_set = 1;
                    clr_poly_clr = 1;
                    clr_twiddle_clr = 1;
                end
                else begin
                    ctr3_inc = 1;
                    ctr1_inc = 1;
                end
            end
        end
        ST_TWIDDLE_OUT: begin
            twiddle_ram_ren = 1;
            p_ren = 1;
            twiddle_poly_idx = 1;
            ctr1_inc = 1;
            o_valid = (O_VALID_EARLY) ? 1 : 0;
            next_state = ST_TWIDDLE_OUT1;
        end
        ST_TWIDDLE_OUT1: begin
            twiddle_ram_ren = o_read;
            p_ren = o_read;
            twiddle_poly_idx = 1;
            o_valid = 1;
            o_data = twiddle_ram_dout;
            zerotwiddle = clr_twiddle_q; //TODO:non-functional now
            if (o_read) begin
                if (ctr3 == n_m1) begin
                    next_state = ST_IDLE;
                    ctr_all_rst = 1;
                    done_set = 1;
                    clr_twiddle_clr = 1;
                end
                else begin
                    ctr3_inc = 1;
                    ctr1_inc = 1;
                end
            end
        end

    endcase


    // common logic for background BU input/output below

    if (ntt_rcv_bu) begin
        if (ntt_o_valid) begin
            if (ctr0 == logn_m1_shft_m1_ctr2) begin
                ctr0_rst = 1;
            end
            else begin
                ctr0_inc = 1;
            end
            if (is_chk_l1norm_q && chknorm_bu) begin
                chknorm_set = 1;
                next_state = ST_IDLE;
                ctr_all_rst = 1;
                done_set = 1;
            end
        end
    end
    else if (pwm_rcv_bu) begin
        if (pwop_o_valid) begin
            if (ctr0 == n_m1) begin
                ctr0_rst = 1;
            end
            else begin
                ctr0_inc = 1;
            end
            if (is_chk_infnorm_q) begin
                if (chknorm_bu) begin
                    chknorm_set = 1;
                    done_set   = 1;
                    next_state = ST_IDLE;
                    ctr_all_rst = 1;
                end
            end
            else begin
                upoly_mul = 1;
                if (is_decompose_q) begin
                    upsi = 1;
                end                
            end
        end
    end
    else if (encode_rcv_bu) begin
        if (encode_o_valid) begin
            upoly_encode = 1;
            ctr1_inc = 1;
        end
    end
end




