`include "ntt_lite.vh"

module ntt_lite
   #(   
        parameter LOGN       = 4,
        parameter LOGQ       = 32,
        parameter W          = 16,
        parameter B          = 32, // bandwidth, must divide LOGQ
        parameter L          = 8, // BU latency
        parameter EN_NTT_OTF = 1
    )
    (
        input                       clk    ,
        input                       rst    ,
        input      [           2:0] cmd    ,
        input      [           1:0] op     ,
        input                       otf    ,
        input      [   LOGLOGN-1:0] logn   ,
        input      [   LOGLOGQ-1:0] logq   ,
        input      [      LOGQ-1:0] q      ,
        input      [      LOGQ+1:0] mu     ,
        input      [           1:0] mode   ,
        input      [         B-1:0] i_data ,
        output reg                  i_ready,
        input                       i_valid,
        output reg [         B-1:0] o_data ,
        input                       o_read ,

        output reg                  o_valid,
        output reg [LOGN+LOGWB-1:0] io_word,
        output reg                  done   ,
        output reg                  busy   ,
        output reg                  error
   );

///////////////////// input checks //////////////////////////////////////

if (LOGQ != B) begin
    LOGQ_MUST_BE_EQUAL_TO_B();
end

/////////////////////////////////////////////////////////////////////////




///////////////////// local parameters //////////////////////////////////

localparam LOGLOGQ = $rtoi($ceil($clog2(LOGQ + 1)));
localparam N       = 1 << LOGN;
localparam LOGLOGN = $rtoi($ceil($clog2(LOGN+1))); 
localparam LOGWB   = $clog2(LOGQ/B);
localparam WBMASK  = (1 << LOGWB) - 1;

// states, todo: add glitch protection as HW codes
localparam ST_IDLE         = 4'd0;
localparam ST_TWIDDLE      = 4'd2;
localparam ST_POLY_IN      = 4'd3;
localparam ST_NTT0         = 4'd4;
localparam ST_NTT1         = 4'd5;
localparam ST_POLY_OUT     = 4'd6;
localparam ST_PWM0         = 4'd7;
localparam ST_PWM1         = 4'd8;
localparam ST_NTT_OTF      = 4'd10;
localparam ST_TWIDDLE_OTF  = 4'd11;

/////////////////////////////////////////////////////////////////////////




///////////////////// signal declarations ///////////////////////////////

// data registers
reg [LOGQ-1:0] psi_delta [0:LOGN-1];

// control registers
reg  [3:0]   state;
reg  [LOGN+LOGWB-1:0] ctr0; // general purpose counter 0,
reg  [LOGN+LOGWB-1:0] ctr1; // general purpose counter 1
reg  [LOGN      -1:0] ctr2; // general purpose counter 2
reg  [LOGLOGN   -1:0] ctr3; // counter 3, used for NTT OTF
wire [LOGN      -1:0] maskS; // stage mask
wire [LOGN      -1:0] maskIS; // stage inv. mask

// control signals generated by FSM
reg [3:0] next_state;
reg ctr0_inc, ctr0_rst;
reg ctr1_inc, ctr1_rst;
reg ctr2_inc, ctr2_rst;
reg ctr3_inc, ctr3_rst;
reg [LOGN+LOGWB-1:0] ctr0_d;
reg [LOGN-1:0] ctr2_d;
reg ctr2_d_set;
reg wpoly, upoly_ntt, upoly_intt, upoly_mul, wpsi, wpsi_delta, upsi, wq, pwm_idx;
reg ntt_rcv_bu, pwm_rcv_bu, ntt_otf_rcv_bu, ntt_otf_feed_bu;
reg ctr_all_rst;
reg done_set;
reg o_valid_int;


// logn register
wire [LOGN  :0] n;
wire [LOGN-1:0] n_m1;
wire [LOGN-1:0] n_m2;
wire [LOGLOGN-1:0] logn_m1;
wire [LOGN   -1:0] n_over2;
wire [LOGN   -2:0] n_over4;
wire [LOGN   -1:0] logn_m1_shft_m1;
wire [LOGN+LOGWB  :0] num_words;
wire [LOGN+LOGWB-1:0] num_words_m1;
wire [LOGN+LOGWB-1:0] num_words_over2;
wire [LOGN+LOGWB-1:0] num_words_over2_m1;


// error register
reg error_set;

// pseudo modes
wire ntt_otf;

// buttefly inputs
wire [LOGQ-1:0] A_i;
wire [LOGQ-1:0] B_i;
wire [LOGQ-1:0] psi_i;
wire [LOGQ-1:0] A_o;
wire [LOGQ-1:0] B_o;
wire [LOGQ-1:0] M_o;

reg  sr_i;
wire sr_o;


// bram signals
wire coeff_ram_p0_wen;
wire [LOGN-1:0] coeff_ram_p0_waddr;
wire [LOGQ-1:0] coeff_ram_p0_din;
wire [LOGN-1:0] coeff_ram_p0_raddr;
wire [LOGQ-1:0] coeff_ram_p0_dout;
wire coeff_ram_p1_wen;
wire [LOGN-1:0] coeff_ram_p1_waddr;
wire [LOGQ-1:0] coeff_ram_p1_din;
wire [LOGN-1:0] coeff_ram_p1_raddr;
wire [LOGQ-1:0] coeff_ram_p1_dout;
wire twiddle_ram_wen;
wire [LOGN-1:0] twiddle_ram_waddr;
wire [LOGQ-1:0] twiddle_ram_din;
wire [LOGN-1:0] twiddle_ram_raddr;
wire [LOGQ-1:0] twiddle_ram_dout;

/////////////////////////////////////////////////////////////////////////




///////////////////// Comb. Logic for N/LOGN/LOGLOGN ////////////////////

assign n = 1 << logn;
assign n_m1 = n - 1;
assign n_m2 = n - 2;
assign logn_m1 = logn - 1;
assign n_over2 = 1 << logn_m1;
assign n_over4 = n_over2 >> 1;
assign logn_m1_shft_m1 = n_over2 - 1;
assign num_words = ((LOGQ/B) << logn);
assign num_words_m1 = num_words - 1;
assign num_words_over2 = num_words >> 1;
assign num_words_over2_m1 = num_words_over2 - 1;

/////////////////////////////////////////////////////////////////////////




///////////////////// BU inputs /////////////////////////////////////////

assign A_i      = coeff_ram_p0_dout;
assign B_i      = (ntt_otf_feed_bu && EN_NTT_OTF) ? psi_delta[ctr3] : coeff_ram_p1_dout;
assign psi_i    = twiddle_ram_dout;

/////////////////////////////////////////////////////////////////////////




///////////////////// Pseudo Modes //////////////////////////////////////

assign ntt_otf = (EN_NTT_OTF) ? ((op == `OP_NTT)||(op == `OP_INTT)) && (otf) : 0;

/////////////////////////////////////////////////////////////////////////




///////////////////// bram signals //////////////////////////////////////

assign coeff_ram_p0_wen   =  wpoly | upoly_mul | upoly_ntt;
assign coeff_ram_p0_waddr = (wpoly     ) ?   ctr1       : 
                            (upoly_mul ) ?   ctr1       : 
                            (upoly_ntt ) ?  (ctr1 << 1) : 
                          /*(upoly_intt) ?*/ ctr1 /*   : 0*/;
assign coeff_ram_p0_din   = (wpoly                   ) ?   i_data : 
                            (upoly_mul               ) ?   M_o    : 
                          /*(upoly_ntt | upoly_intt  ) ?*/ A_o  /*: 0*/;
assign coeff_ram_p0_raddr = (op == `OP_INTT) ? (ctr0 << 1)  : 
                                                    ctr0        ;

assign coeff_ram_p1_wen   =  upoly_ntt | upoly_intt;
assign coeff_ram_p1_waddr = (upoly_ntt ) ?  (ctr1 << 1) + 1   : 
                          /*(upoly_intt) ?*/ ctr1 + n_over2 /*: 0*/;
assign coeff_ram_p1_din   =  B_o;
assign coeff_ram_p1_raddr = (pwm_idx             ) ?  ctr0             : 
                            (op == `OP_INTT      ) ? ((ctr0 << 1) + 1) :  
                                                     (ctr0 + n_over2)  ;
// todo: check pwm_idx, use `OP_PWM if posslbe

assign maskS    = (1 << ctr2) - 1 ;
assign maskIS   = (1 << (logn_m1 - ctr2)) - 1;

assign twiddle_ram_wen   =  wpsi | upsi;
assign twiddle_ram_waddr = (wpsi) ? ctr0 : /*(upsi) ?*/ ctr1/* : 0*/;
assign twiddle_ram_din   = (wpsi) ? i_data : /*(upsi) ?*/ M_o/* : 0*/;
assign twiddle_ram_raddr = (EN_NTT_OTF && ntt_otf_feed_bu) ?                    ctr2            : 
                           (pwm_idx                      ) ?                    ctr0            : 
                           (op == `OP_INTT               ) ? ((~maskIS << 1) + (ctr0 & maskIS)) : 
                                                             (  maskS        + (ctr0 & maskS )) ; 

/////////////////////////////////////////////////////////////////////////




///////////////////// Sequential Logic //////////////////////////////////


if (EN_NTT_OTF) begin
    for(genvar i = 0; i < LOGN ;i = i + 1) begin: TWIDDLE_LOAD_GEN
        for(genvar j = 0; j < (LOGQ/B); j = j + 1) begin
            always @(posedge clk) begin
                if (wpsi_delta && (ctr0 == (i*(LOGQ/B) + j)))
                    psi_delta[i][j*B +: B] <= i_data;
            end
        end
    end
end


always @(posedge clk) begin
    if (rst)
        ctr0 <= 0;
    else if (ctr0_inc)
        ctr0 <= ctr0 + 1;
    else if (ctr0_rst || ctr_all_rst)
        ctr0 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr1 <= 0;
    else if (ctr1_inc)
        ctr1 <= ctr1 + 1;
    else if (ctr1_rst || ctr_all_rst)
        ctr1 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr2 <= 0;
    else if (ctr2_inc)
        ctr2 <= ctr2 + 1;
    else if (ctr2_rst || ctr_all_rst)
        ctr2 <= 0;
end

if (EN_NTT_OTF) begin
    always @(posedge clk) begin
        if (rst)
            ctr3 <= 0;
        else if (ctr3_inc)
            ctr3 <= ctr3 + 1;
        else if (ctr3_rst || ctr_all_rst)
            ctr3 <= 0;
    end
end


always @(posedge clk) begin
    ctr0_d <= ctr0;
end


always @(posedge clk) begin
    if (rst)
        ctr2_d <= 0;
    else if (ctr2_d_set) //todo: check if needed
        ctr2_d <= ctr2;
end


always @(posedge clk) begin
    if (rst)
        state <= ST_IDLE;
    else
        state <= next_state;
end


always @(posedge clk) begin
    if (rst)
        done <= 0;
    else if (done_set)
        done <= 1;
    else if (done)
        done <= 0;
end


always @(posedge clk) begin
    if (rst)
        error <= 0;
    else if (error_set)
        error <= 1;
    else if (error)
        error <= 0;
end


always @(posedge clk) begin
    if (rst)
        o_valid <= 0;
    else
        o_valid <= o_valid_int;
end




