butterfly 
    #(
        .LOGQ(LOGQ),
        .LOGQH(LOGQ-W),
        .L(L)
    ) btfu
    (
        .clk(clk  ),
        .mode(mode_q),
        .A  (A_i  ),
        .B  (B_i  ),
        .PSI(psi_i),
        .q  (q    ),
        .qW (qW   ),
        .E  (A_o  ),
        .O  (B_o  ),
        .M  (M_o  )
    );


shiftreg 
   #(
        .SHIFT(L),
        .DATA (1)
    ) 
shreg 
    (
        .clk     (clk ),
        .rst     (rst ),
        .data_in (sr_i),
        .data_out(sr_o)
    );




///////////////////// FSM ///////////////////////////////////////////////


always @(*) begin

    next_state = state;
    ctr0_inc = 0;
    ctr0_rst = 0;
    ctr1_inc = 0;
    ctr1_rst = 0;
    ctr2_inc = 0;
    ctr2_rst = 0;
    ctr2_d_set = 0;
    ctr3_inc = 0;
    ctr3_rst = 0;
    wpoly = 0;
    upoly_ntt = 0;
    upoly_intt = 0;
    upoly_mul = 0;
    wpsi = 0;
    wpsi_delta = 0;
    upsi = 0;
    wq = 0;
    sr_i = 0;
    busy = 0;
    o_data = {B{1'b0}};
    o_valid = 0;
    mode_set = 0;
    otf_set = 0;
    pwm_idx = 0;
    ntt_rcv_bu = 0;
    pwm_otf_feed_bu = 0;
    ntt_otf_feed_bu = 0;
    pwm_otf_rcv_bu = 0;
    ntt_otf_rcv_bu = 0;
    pwm_rcv_bu = 0;
    ctr_all_rst = 0;
    done_set = 0;
    error_set = 0;
    poly_psi_rst = 0;
    io_word = 0;
    i_ready = 0;
    logq_set = 0;

    case (state)
        ST_IDLE: begin
            if (cmd == `CMD_LOAD_Q) begin
                next_state = ST_Q;
                logq_set = 1;
                if (i_valid) begin
                    ctr0_inc = 1;
                    wq = 1;
                end
            end
            else if (cmd == `CMD_LOAD_TWIDDLE) begin
                if (logn > LOGN) begin
                    error_set = 1;
                    next_state = ST_IDLE;
                end
                else begin
                    next_state = ST_TWIDDLE;
                    otf_set = 1;
                    logn_set = 1;
                end
            end
            else if (cmd == `CMD_LOAD_POLY) begin
                if (logn > LOGN) begin
                    error_set = 1;
                    next_state = ST_IDLE;
                end
                else begin
                    next_state = ST_POLY_IN;
                    mode_set = 1;
                    otf_set = 1;
                    logn_set = 1;
                end
            end
            else if (cmd == `CMD_RST) begin
                next_state = ST_IDLE;
                ctr_all_rst = 0;
                poly_psi_rst = 1;
                done_set = 1;
            end

        end
        ST_Q: begin

            io_word = ctr0;
            i_ready = 1;
            if (i_valid) begin
                wq = 1;
                if (ctr0 == ((LOGQ/B) - 1)) begin
                    next_state = ST_IDLE;
                    ctr0_rst = 1;
                    done_set = 1;
                end
                else
                    ctr0_inc = 1;
            end

        end
        ST_TWIDDLE: begin

            io_word = ctr0;
            i_ready = 1;
            if (i_valid) begin
                wpsi = 1;
                if (ctr0 == num_words_m1) begin
                    if (EN_NTT_OTF && otf_q) begin
                        next_state = ST_TWIDDLE_OTF;
                    end
                    else begin
                        next_state = ST_IDLE;
                        done_set = 1;
                    end
                    ctr0_rst = 1;
                end
                else
                    ctr0_inc = 1;
            end

        end
        ST_TWIDDLE_OTF: begin // todo: check here

            io_word = ctr0 + num_words;
            i_ready = 1;
            if (i_valid) begin
                wpsi_delta = 1;
                if (ctr0 == num_words_m1) begin
                    next_state = ST_IDLE;
                    ctr0_rst = 1;
                    done_set = 1;
                end
                else
                    ctr0_inc = 1;
            end

        end
        ST_POLY_IN: begin

            io_word = ctr1;
            i_ready = 1;
            if (i_valid) begin
                wpoly = 1;
                if (pwm_otf && (ctr1 == num_words_over2_m1)) begin
                    next_state = ST_PWM0;
                    ctr1_rst = 1;
                end
                else if (ctr1 == num_words_m1) begin
                    next_state = ((mode_q == `MODE_NTT)||(mode_q == `MODE_INTT)) ? ST_NTT0 : (mode_q == `MODE_PWM) ? ST_PWM0 : ST_IDLE;
                    ctr1_rst = 1;
                end
                else
                    ctr1_inc = 1;
            end

        end
        ST_PWM0: begin

            pwm_idx = 1;
            busy = 1;
            sr_i = 1;
            if (((otf_q == 1) && (ctr0 == logn_m1_shft_m1)) || (ctr0 == n_m1)) begin
                ctr0_rst = 1;
                next_state = ST_PWM1;
                ctr2_rst = 1;
            end
            else
                ctr0_inc = 1;

            pwm_rcv_bu = 1;

        end
        ST_PWM1: begin

            busy = 1;
            if (((otf_q == 1) && (ctr1 == logn_m1_shft_m1)) || (ctr1 == n_m1)) begin
                next_state = ST_POLY_OUT;
            end

            pwm_rcv_bu = 1;

            if (otf_q == 1)begin
                pwm_otf_feed_bu = 1;
            end
        end
        ST_NTT0: begin

            busy = 1;
            sr_i = 1;
            if (ctr0 == logn_m1_shft_m1) begin
                ctr0_rst = 1;
                next_state = ST_NTT1;
                ctr2_d_set = 1;
                if (EN_NTT_OTF && (ctr2 == logn_m1)) begin
                    ctr2_rst = 1;
                end
            end
            else
                ctr0_inc = 1;

            ntt_rcv_bu = 1;
        end
        ST_NTT1: begin

            busy = 1;
            // BU input for next stage is valid after processing half of the poly
            if ((ctr1 >= n_over4) && (ctr2_d != logn_m1)) begin
                next_state = ST_NTT0;
                ctr2_inc = 1; // go to next stage
            end
            else if (/*!PRLLOUT && */(ctr1 == logn_m1_shft_m1)) begin
                    next_state = ST_POLY_OUT;
            end

            if (otf_q == 1 && (ctr2_d == logn_m1))begin
                ntt_otf_feed_bu = 1;
            end
            ntt_rcv_bu = 1;

        end
        
        ST_POLY_OUT: begin

            io_word = ctr0;
            o_valid = 1;
            o_data = poly[ctr0 >> LOGWB][(ctr0 & WBMASK) * B +: B];
            busy = 1;
            if (o_read) begin
                if (pwm_otf && (ctr0 == num_words_over2_m1)) begin
                    if (ctr1 == n_over2) begin
                        next_state = ST_IDLE;
                        ctr_all_rst = 1;
                        done_set = 1;
                    end
                    else begin
                        next_state = ST_PWM_OTF;
                    end
                    ctr0_rst = 1;
                end
                else if (ctr0 == num_words_m1) begin
                    if (ntt_otf) begin
                        if (ctr1 == n_m1) begin
                            next_state = ST_IDLE;
                            ctr_all_rst = 1;
                            done_set = 1;
                        end
                        else begin
                            next_state = ST_NTT_OTF;
                        end
                        ctr0_rst = 1;
                    end
                    else begin
                        next_state = ST_IDLE;
                        ctr_all_rst = 1;
                        done_set = 1;
                    end
                end
                else
                    ctr0_inc = 1;
            end

            if (ntt_otf) begin
                ntt_otf_feed_bu = 1;
                ntt_otf_rcv_bu = 1;
            end
            else if (pwm_otf) begin
                pwm_otf_feed_bu = 1;
                pwm_otf_rcv_bu = 1;
            end


        end
        ST_PWM_OTF: begin
        // we do not feed the twiddles in this stage. because, it is mathematically guaratneed that all the twiddles are fed for OTF in the ST_POLY_OUT state.
        // note that at least N read will be done, while N/2 twiddles will be fed to BU.
            if (EN_PWM_OTF) begin
                busy = 1;

                if (ctr1 == n_over2) begin
                    next_state = ST_IDLE;
                    ctr_all_rst = 1;
                    done_set = 1;
                end

                pwm_otf_rcv_bu = 1;
            end
        end
        ST_NTT_OTF: begin
        // we do not feed the twiddles in this stage. because, it is mathematically guaratneed that all the twiddles are fed for OTF in the ST_POLY_OUT state.
        // note that at least N read will be done, while N/2 twiddles will be fed to BU.
            if (EN_NTT_OTF) begin
                busy = 1;

                if (ctr1 == n_m1) begin
                    next_state = ST_IDLE;
                    ctr_all_rst = 1;
                    done_set = 1;
                end

                ntt_otf_rcv_bu = 1;
            end
        end

    endcase


    // common logic for background BU input/output below

    if (EN_NTT_OTF && ntt_otf_feed_bu) begin
        if (ctr2 <= n_m2) begin
            ctr2_inc = 1;
            sr_i = 1;
        end
        if ((((ctr2 + 2) >> (ctr3 + 1)) & 1'b1) && ctr2 < n_m2) begin
            ctr3_inc = 1;
        end
    end
    else if (EN_PWM_OTF && pwm_otf_feed_bu) begin
        if (ctr2 <= logn_m1_shft_m1) begin
            ctr2_inc = 1;
            sr_i = 1;
        end
    end

    if (ntt_rcv_bu) begin
        if (sr_o) begin
            if (ctr1 == logn_m1_shft_m1) begin
                ctr1_rst = 1;
            end
            else
                ctr1_inc = 1;
            upoly_ntt = (mode == `MODE_NTT);
            upoly_intt = (mode == `MODE_INTT);
        end
    end
    else if (pwm_rcv_bu) begin
        if (sr_o) begin
            if (EN_PWM_OTF && otf_q == 1 && (ctr1 == logn_m1_shft_m1)) begin
                ctr1_rst = 1;
            end
            else
                ctr1_inc = 1;
            upoly_mul = 1;
        end
    end
    else if (EN_NTT_OTF && ntt_otf_rcv_bu) begin
        if (sr_o) begin
            upsi = 1;
            if (ctr1 <= n_m2) begin
                ctr1_inc = 1;
            end
        end
    end
    else if (EN_PWM_OTF && pwm_otf_rcv_bu) begin
        if (sr_o) begin
            upsi = 1;
            if (ctr1 <= logn_m1_shft_m1) begin
                ctr1_inc = 1;
            end
        end
    end


end

