`include "ntt_lite.vh"

module ntt_lite
   #(   
        parameter LOGN       = 4,
        parameter LOGQ       = 64,
        parameter W          = 16,
        parameter B          = 32, // bandwidth, must divide LOGQ
        parameter L          = 13, // BU latency
        parameter EN_NTT_OTF = 1,  // enable NTT OTF
        parameter EN_PWM_OTF = 0   // enable PWM OTF
    )
    (
        input                       clk    ,
        input                       rst    ,
        input      [           2:0] cmd    ,
        input      [           1:0] mode   ,
        input                       otf    ,
        input      [   LOGLOGN-1:0] logn   ,
        input      [           1:0] logq   ,
        input      [         B-1:0] i_data ,
        output reg                  i_ready,
        input                       i_valid,
        output reg [         B-1:0] o_data ,
        input                       o_read ,

        output reg                  o_valid,
        output reg [LOGN+LOGWB-1:0] io_word,
        output reg                  done   ,
        output reg                  busy   ,
        output reg                  error
    );

localparam N       = 1 << LOGN;
localparam LOGLOGN = $rtoi($ceil($clog2(LOGN+1))); 
localparam LOGWB   = $clog2(LOGQ/B);
localparam WBMASK  = (1 << LOGWB) - 1;
localparam QW      = $rtoi($ceil(LOGQ / W));
localparam LOGQW   = $rtoi($ceil($clog2(QW + 1)));

// states, todo: add glitch protection as HW codes
localparam ST_IDLE         = 4'd0;
localparam ST_Q            = 4'd1;
localparam ST_TWIDDLE      = 4'd2;
localparam ST_POLY_IN      = 4'd3;
localparam ST_NTT0         = 4'd4;
localparam ST_NTT1         = 4'd5;
localparam ST_POLY_OUT     = 4'd6;
localparam ST_PWM0         = 4'd7;
localparam ST_PWM1         = 4'd8;
localparam ST_PWM_OTF      = 4'd9;
localparam ST_NTT_OTF      = 4'd10;
localparam ST_TWIDDLE_OTF  = 4'd11;


///////////////////// signal declarations ///////////////////////////////


// data registers
reg [LOGQ-1:0] poly [0:N-1];
reg [LOGQ-1:0] psi  [0:N-1];
reg [LOGQ-1:0] q;
reg [LOGQ-1:0] psi_delta [0:LOGN-1];

// control registers
reg  [3:0]   state;
reg  [LOGN+LOGWB-1:0] ctr0; // general purpose counter 0,
reg  [LOGN+LOGWB-1:0] ctr1; // general purpose counter 1
reg  [LOGN      -1:0] ctr2; // general purpose counter 2
reg  [LOGLOGN   -1:0] ctr3; // counter 3, used for NTT OTF
wire [LOGN      -1:0] maskS; // stage mask
wire [LOGN      -1:0] maskIS; // stage inv. mask

// control signals generated by FSM
reg [3:0] next_state;
reg ctr0_inc, ctr0_rst;
reg ctr1_inc, ctr1_rst;
reg ctr2_inc, ctr2_rst;
reg ctr3_inc, ctr3_rst;
reg [LOGN-1:0] ctr2_d;
reg ctr2_d_set;
reg wpoly, upoly_ntt, upoly_intt, upoly_mul, wpsi, wpsi_delta, upsi, wq, pwm_idx;
reg poly_psi_rst;
reg otf_q, otf_set;
reg ntt_rcv_bu, pwm_rcv_bu, pwm_otf_rcv_bu, ntt_otf_rcv_bu, ntt_otf_feed_bu, pwm_otf_feed_bu;
reg ctr_all_rst;
reg done_set;

// mode register
reg [1:0] mode_q;
reg mode_set;

// logn register
wire [LOGN  :0] n;
wire [LOGN-1:0] n_m1;
wire [LOGN-1:0] n_m2;
reg  [LOGLOGN-1:0] logn_q;
wire [LOGLOGN-1:0] logn_m1;
wire [LOGN   -1:0] n_over2;
wire [LOGN   -2:0] n_over4;
wire [LOGN   -1:0] logn_m1_shft_m1;
wire [LOGN+LOGWB  :0] num_words;
wire [LOGN+LOGWB-1:0] num_words_m1;
wire [LOGN+LOGWB-1:0] num_words_over2;
wire [LOGN+LOGWB-1:0] num_words_over2_m1;

reg  logn_set;

reg [1:0] logq_q;
reg logq_set;

// error register
reg error_set;

// pseudo modes
wire pwm_otf;
wire ntt_otf;

// buttefly inputs
wire [LOGN-1:0] poly_ida;
wire [LOGN-1:0] poly_idb;
wire [LOGN-1:0] psi_idx;

wire [LOGQ-1:0] A_i;
wire [LOGQ-1:0] B_i;
wire [LOGQ-1:0] psi_i;
wire [LOGQ-1:0] A_o;
wire [LOGQ-1:0] B_o;
wire [LOGQ-1:0] M_o;
wire [LOGQW-1:0] qW;
reg  sr_i;
wire sr_o;


/////////////////////////////////////////////////////////////////////////




///////////////////// Comb. Logic for N/LOGN/LOGLOGN ////////////////////

assign n = 1 << logn_q;
assign n_m1 = n - 1;
assign n_m2 = n - 2;
assign logn_m1 = logn_q - 1;
assign n_over2 = 1 << logn_m1;
assign n_over4 = n_over2 >> 1;
assign logn_m1_shft_m1 = n_over2 - 1;
assign num_words = ((LOGQ/B) << logn_q);
assign num_words_m1 = num_words - 1;
assign num_words_over2 = num_words >> 1;
assign num_words_over2_m1 = num_words_over2 - 1;

/////////////////////////////////////////////////////////////////////////




///////////////////// BU address generation /////////////////////////////

assign maskS    = (1 << ctr2) - 1 ; // can be computed sequentially // not parametric
assign maskIS    = (1 << (logn_m1 - ctr2)) - 1; // can be computed sequentially 
assign poly_ida = (mode_q == `MODE_INTT) ? (ctr0 << 1) : ctr0;
assign poly_idb = (ntt_otf_feed_bu && EN_NTT_OTF) ? ctr3 : (EN_PWM_OTF && pwm_otf_feed_bu) ? (ctr2 + n_over2) : (pwm_idx) ? ctr0 : (mode_q == `MODE_INTT) ? ((ctr0 << 1) + 1) :  (ctr0 + n_over2);
assign psi_idx  = ((EN_PWM_OTF && pwm_otf_feed_bu) || (ntt_otf_feed_bu && EN_NTT_OTF)) ? ctr2 : (pwm_idx) ? ctr0 : (mode_q == `MODE_INTT) ? ((~maskIS << 1) +(ctr0 & maskIS)) : (maskS + (ctr0 & maskS)); 
assign A_i      = poly[poly_ida];
assign B_i      = (ntt_otf_feed_bu && EN_NTT_OTF) ? psi_delta[poly_idb] : (EN_PWM_OTF && pwm_otf_feed_bu) ? psi[poly_idb] : poly[poly_idb];
assign psi_i    = psi[psi_idx];

/////////////////////////////////////////////////////////////////////////




///////////////////// modulus conf. for butterfly ///////////////////////

assign qW    = (logq_q == `LOGQ_64) ? 3'd4 : 3'd2;

/////////////////////////////////////////////////////////////////////////




///////////////////// Pseudo Modes //////////////////////////////////////

assign pwm_otf = (EN_PWM_OTF) ? (mode_q == `MODE_PWM) && (otf_q) : 0;
assign ntt_otf = (EN_NTT_OTF) ? ((mode_q == `MODE_NTT)||(mode_q == `MODE_INTT)) && (otf_q) : 0;

/////////////////////////////////////////////////////////////////////////




///////////////////// Sequential Logic //////////////////////////////////


for(genvar i = 0; i < N ;i = i + 1) begin: TWIDDLE_LOAD_GEN
    for(genvar j = 0; j < (LOGQ/B); j = j + 1) begin
        always @(posedge clk) begin
            if (rst) // todo add reset
                psi[i][j*B +: B] <= 0;
            else if (poly_psi_rst)
                psi[i][j*B +: B] <= 0;
            else if (wpsi && (ctr0 == (i*(LOGQ/B) + j)))
                psi[i][j*B +: B] <= i_data;
            else if (upsi && (ctr1 == i))
                psi[i][j*B +: B] <= M_o >> (j*B);
        end
    end
end


if (EN_NTT_OTF) begin
    for(genvar i = 0; i < LOGN ;i = i + 1) begin: TWIDDLE_LOAD_GEN
        for(genvar j = 0; j < (LOGQ/B); j = j + 1) begin
            always @(posedge clk) begin
                if (rst) // todo add reset
                    psi_delta[i][j*B +: B] <= 0;
                else if (poly_psi_rst)
                    psi_delta[i][j*B +: B] <= 0;
                else if (wpsi_delta && (ctr0 == (i*(LOGQ/B) + j)))
                    psi_delta[i][j*B +: B] <= i_data;
            end
        end
    end
end

for(genvar i = 0; i < N ;i = i + 1) begin: POLY_GEN
    for(genvar j = 0; j < (LOGQ/B); j = j + 1) begin
        always @(posedge clk) begin
            if (rst)
                poly[i][j*B +: B] <= 0;
            else if (poly_psi_rst)
                poly[i][j*B +: B] <= 0;
            else if (upoly_mul && (ctr1 == i))
                poly[i][j*B +: B] <= M_o >> (j*B);
            else if (upoly_ntt && ((ctr1 << 1) == i))
                poly[i][j*B +: B] <= A_o >> (j*B);
            else if (upoly_ntt && (((ctr1 << 1) + 1) == i))
                poly[i][j*B +: B] <= B_o >> (j*B);
            else if (upoly_intt && (ctr1 == i))
                poly[i][j*B +: B] <= A_o >> (j*B);
            else if (upoly_intt && ((ctr1 + n_over2) == i) )
                poly[i][j*B +: B] <= B_o >> (j*B);
            else if (wpoly && ctr1 == (i*(LOGQ/B) + j))
                poly[i][j*B +: B] <= i_data;
        end
    end
end


for(genvar j = 0; j < (LOGQ/B); j = j + 1) begin
    always @(posedge clk) begin
        if (rst)
            q[j*B +: B] <= 0;
        else if (wq && ctr0 == j)
            q[j*B +: B] <= i_data;
    end
end


always @(posedge clk) begin
    if (rst)
        ctr0 <= 0;
    else if (ctr0_inc)
        ctr0 <= ctr0 + 1;
    else if (ctr0_rst || ctr_all_rst)
        ctr0 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr1 <= 0;
    else if (ctr1_inc)
        ctr1 <= ctr1 + 1;
    else if (ctr1_rst || ctr_all_rst)
        ctr1 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr2 <= 0;
    else if (ctr2_inc)
        ctr2 <= ctr2 + 1;
    else if (ctr2_rst || ctr_all_rst)
        ctr2 <= 0;
end

if (EN_NTT_OTF) begin
    always @(posedge clk) begin
        if (rst)
            ctr3 <= 0;
        else if (ctr3_inc)
            ctr3 <= ctr3 + 1;
        else if (ctr3_rst || ctr_all_rst)
            ctr3 <= 0;
    end
end

always @(posedge clk) begin
    if (rst)
        ctr2_d <= 0;
    else if (ctr2_d_set)
        ctr2_d <= ctr2;
end


always @(posedge clk) begin
    if (rst)
        state <= ST_IDLE;
    else
        state <= next_state;
end


always @(posedge clk) begin
    if (rst)
        mode_q <= 0;
    else if (mode_set)
        mode_q <= mode;
end


always @(posedge clk) begin
    if (rst)
        otf_q <= 0;
    else if (otf_set)
        otf_q <= otf;
end


always @(posedge clk) begin
    if (rst)
        logn_q <= 0;
    else if (logn_set)
        logn_q <= logn;
end


always @(posedge clk) begin
    if (rst)
        logq_q <= 0;
    else if (logq_set)
        logq_q <= logq;
end



always @(posedge clk) begin
    if (rst)
        done <= 0;
    else if (done_set)
        done <= 1;
    else if (done)
        done <= 0;
end


always @(posedge clk) begin
    if (rst)
        error <= 0;
    else if (error_set)
        error <= 1;
    else if (error)
        error <= 0;
end


