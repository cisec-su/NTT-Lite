///////////////////// FSM ///////////////////////////////////////////////


always @(*) begin

    next_state = state;
    ctr0_inc = 0;
    ctr0_rst = 0;
    ctr1_inc = 0;
    ctr1_rst = 0;
    ctr2_inc = 0;
    ctr2_rst = 0;
    ctr2_d_set = 0;
    ctr3_inc = 0;
    ctr3_rst = 0;
    wpoly = 0;
    upoly_ntt = 0;
    upoly_intt = 0;
    upoly_mul = 0;
    wpsi = 0;
    wpsi_delta = 0;
    upsi = 0;
    wq = 0;
    sr_i = 0;
    busy = 0;
    o_valid_int = 0;
    pwm_idx = 0;
    ntt_rcv_bu = 0;
    sum_rcv_bu = 0;
    addsub_rcv_bu = 0;
    pwm_rcv_bu = 0;
    encode_rcv_bu = 0;
    ctr_all_rst = 0;
    done_set = 0;
    error_set = 0;
    // io_word = 0;
    i_ready = 0;

    coeff_ram_p0_rsel = 0;
    coeff_ram_p0_wsel = 0;

    o_data = (twiddle_out_q) ? twiddle_ram_dout : coeff_ram_p0_dout; // will change
    io_word = ctr0_d; // will change

    encode_rst = 0;
    upoly_encode = 0;

    twiddle_out_set = 0;

    chknorm_set = 0;

    poly_in_frwrd_A = 0;
    poly_in_frwrd_B = 0;
    twiddle_frwrd = 0;

    case (state)
        ST_IDLE: begin
            if (cmd == `CMD_LOAD_TWIDDLE) begin
                if (logn > LOGN) begin
                    error_set = 1;
                    next_state = ST_IDLE;
                end
                else begin
                    if (op == `OP_ADD || (op == `OP_SUB)) begin
                        next_state = ST_TWIDDLE_FORWARD_ADDSUB;
                    end
                    else if (op == `OP_PWM) begin
                        next_state = ST_TWIDDLE_FORWARD_PWM;
                    end
                    else begin
                        next_state = ST_TWIDDLE_IN;                        
                    end
                end
            end
            else if (cmd == `CMD_LOAD_POLY) begin
                if (logn > LOGN) begin
                    error_set = 1;
                    next_state = ST_IDLE;
                end
                else begin
                    if (next_state_op == ST_PWM0) begin
                        next_state = ST_POLY_FORWARD_PWM;
                    end
                    else if (next_state_op == ST_ENCODE0) begin
                        next_state = ST_POLY_FORWARD_ENCODE;
                    end
                    else if (next_state_op == ST_ADDSUB) begin
                        next_state = ST_POLY_FORWARD_ADDSUB;
                    end
                    else begin
                        next_state = ST_POLY_IN;
                    end
                end
            end
            else if (cmd == `CMD_READ_TWIDDLE) begin
                if (logn > LOGN) begin
                    error_set = 1;
                    next_state = ST_IDLE;
                end
                else begin
                    next_state = ST_TWIDDLE_OUT;
                end
            end            
            else if (cmd == `CMD_RST) begin
                next_state = ST_IDLE;
                ctr_all_rst = 1;
                done_set = 1;
            end
            else if (cmd == `CMD_START) begin
                next_state = next_state_op;
            end

            encode_rst = 1;
        end
        ST_TWIDDLE_IN: begin

            io_word = ctr0;
            i_ready = 1;
            if (i_valid) begin
                wpsi = 1;
                if (ctr0 == num_words_m1) begin
                    next_state = ST_IDLE;
                    done_set = 1;
                    ctr0_rst = 1;
                end
                else
                    ctr0_inc = 1;
            end

        end
        ST_TWIDDLE_FORWARD_ADDSUB: begin

            io_word = ctr0;
            i_ready = 1;
            if (i_valid) begin
                wpsi = 1;
                sr_i = 1;

                if (ctr0 == n_m1) begin
                    next_state = ST_ADDSUB;
                end
                else begin
                    ctr0_inc = 1;
                end
            end

            twiddle_frwrd = 1;
            pwm_idx = 1;
            addsub_rcv_bu = 1;

        end
        ST_TWIDDLE_FORWARD_PWM: begin

            io_word = ctr0;
            i_ready = 1;
            if (i_valid) begin
                wpsi = 1;
                sr_i = 1;

                if (ctr0 == n_m1) begin
                    next_state = ST_PWM1;
                    ctr0_rst = 1;
                end
                else
                    ctr0_inc = 1;
            end


            twiddle_frwrd = 1;
            pwm_idx = 1;
            pwm_rcv_bu = 1;

        end
        ST_POLY_IN: begin

            io_word = ctr1;
            i_ready = 1;
            if (i_valid) begin
                wpoly = 1;
                if (ctr1 == num_words_m1) begin
                    next_state = next_state_op;
                    ctr1_rst = 1;
                end
                else if (op == `OP_NTT && ctr1 == num_words_over2_m1) begin
                    next_state = ST_POLY_FORWARD_NTT;
                    ctr1_rst = 1;
                end
                else
                    ctr1_inc = 1;
            end

        end
        ST_POLY_FORWARD_PWM: begin

            io_word = ctr0;
            i_ready = 1;

            if (i_valid) begin
                sr_i = 1;

                if (ctr0 == n_m1) begin
                    next_state = ST_PWM1;
                    ctr0_rst = 1;

                end
                else begin
                    ctr0_inc = 1;
                end
            end

            poly_in_frwrd_B = 1;
            pwm_idx = 1;
            pwm_rcv_bu = 1;

        end
        ST_POLY_FORWARD_ADDSUB: begin

            io_word = ctr0;
            i_ready = 1;

            if (i_valid) begin
                sr_i = 1;

                if (ctr0 == n_m1) begin
                    next_state = ST_ADDSUB;
                end
                else begin
                    ctr0_inc = 1;
                end
            end

            poly_in_frwrd_A = 1;
            pwm_idx = 1;
            addsub_rcv_bu = 1;

        end
        ST_POLY_FORWARD_NTT: begin

            io_word = ctr0 + n_over2;
            i_ready = 1;

            if (i_valid) begin
                sr_i = 1;

                if (ctr0 == n_m1) begin
                    // there is a sim x real_device mismatch if this branch does not exist
                    // which is completely inactive
                end
                else if (ctr0 == logn_m1_shft_m1) begin
                    next_state = ST_NTT1;
                    ctr0_rst = 1;
                    ctr2_d_set = 1;                
                end
                else begin
                    ctr0_inc = 1;
                end
            end

            poly_in_frwrd_B = 1;
            ntt_rcv_bu = 1;

        end
        ST_POLY_FORWARD_ENCODE: begin
            io_word = ctr0;
            i_ready = 1;

            if (i_valid) begin
                sr_i = 1;

                if (ctr0 == n_m1) begin
                    next_state = ST_ENCODE1;
                    ctr0_rst = 1;
                end
                else
                    ctr0_inc = 1;
            end

            poly_in_frwrd_A = 1;
            encode_rcv_bu = 1;

        end
        ST_ENCODE0: begin

            sr_i = 1;
            if (ctr0 == n_m1) begin
                ctr0_rst = 1;
                next_state = ST_ENCODE1;
            end
            else begin
                ctr0_inc = 1;
            end

            encode_rcv_bu = 1;

        end     
        ST_ENCODE1: begin

            if (encode_o_valid) begin
                next_state = ST_ENCODE1;
            end
            else if (!encode_i_valid) begin
                next_state = ST_POLY_OUT;
            end

            encode_rcv_bu = 1;

        end
        ST_DECODE: begin

            pwm_idx = 1;
            if (encode_i_ready && ctr1 != n_m1 && !sr_t) begin
                ctr0_inc = 1;
                sr_i = 1;
            end
            if (encode_o_valid) begin
                upoly_encode = 1;
                if (ctr1 == n_m1) begin
                    ctr1_rst = 1;
                    ctr0_rst = 1;
                    next_state = ST_POLY_OUT;
                end
                else begin
                    ctr1_inc = 1;
                end                
            end

        end
        ST_ADDSUB: begin

            pwm_idx = 1;
            busy = 1;
            sr_i = 1;
            if (ctr0 != n_m1) begin
                ctr0_inc = 1;
            end

            if (sr_t) begin
                if (ctr1 == n_m1) begin
                    ctr0_rst = 1;
                    next_state = ST_POLY_OUT;
                end
            end

            addsub_rcv_bu = 1;
            
        end
        ST_CHKNORM: begin

            pwm_idx = 1;
            busy = 1;
            sr_i = 1;

            if (sr_t) begin
                if (chknorm_bu) begin
                    chknorm_set = 1;
                    done_set   = 1;
                    next_state = ST_IDLE;
                    ctr_all_rst = 1;
                end                
                else if (ctr1 == n_m1) begin
                    ctr_all_rst = 1;
                    done_set   = 1;
                    next_state = ST_IDLE;
                end
                else begin
                    if (ctr0 != n_m1) begin
                        ctr0_inc = 1;
                    end                    
                    ctr1_inc = 1;
                end
            end
            else begin
                if (ctr0 != n_m1) begin
                    ctr0_inc = 1;
                end
            end

        end     
        ST_PWM0: begin

            pwm_idx = 1;
            busy = 1;
            sr_i = 1;
            if (ctr0 == n_m1) begin
                ctr0_rst = 1;
                next_state = ST_PWM1;
            end
            else
                ctr0_inc = 1;

            pwm_rcv_bu = 1;

        end
        ST_PWM1: begin

            busy = 1;
            if ((sr_x && op == `OP_DECOMPRESS) || sr_o) begin
                if (ctr1 == n_m1) begin
                    next_state = ST_POLY_OUT;
                end
            end

            pwm_rcv_bu = 1;

        end
        ST_NTT0: begin

            busy = 1;
            sr_i = 1;
            coeff_ram_p0_rsel = ctr2 & 1'b1;
            if (ctr0 == logn_m1_shft_m1) begin
                ctr0_rst = 1;
                next_state = ST_NTT1;
                ctr2_d_set = 1;
            end
            else
                ctr0_inc = 1;

            ntt_rcv_bu = 1;
        end
        ST_NTT1: begin

            busy = 1;
            // BU input for next stage is valid after processing half of the poly
            if ((ctr1 >= n_over4) && (ctr2_d != logn_m1)) begin
                next_state = ST_NTT0;
                ctr2_inc = 1; // go to next stage
            end
            else if (/*!PRLLOUT && */(ctr1 == logn_m1_shft_m1)) begin
                next_state = ST_POLY_OUT;
            end

            ntt_rcv_bu = 1;

        end
        ST_SUM0: begin

            busy = 1;
            sr_i = 1;
            if (ctr0 == (logn_m1_shft_m1_ctr2)) begin
                ctr0_rst = 1;
                next_state = ST_SUM1;
                ctr2_d_set = 1;
            end
            else begin
                ctr0_inc = 1;                
            end

            sum_rcv_bu = 1;

        end
        ST_SUM1: begin

            busy = 1;
            if ((ctr1 == logn_m1_shft_m1_ctr2)) begin
                if (ctr2_d != logn_m1) begin
                    next_state = ST_SUM0;
                    ctr2_inc = 1; // go to next stage                        
                end
                else begin
                    next_state = ST_POLY_OUT;                    
                end
            end

            sum_rcv_bu = 1;

        end        
        ST_POLY_OUT: begin

            if (!o_dis) begin
                pwm_idx = 1;
                o_valid_int = 1;
                coeff_ram_p0_rsel = (op == `OP_NTT || op == `OP_INTT) ? logn & 1'b1 : 1'b0;
                busy = 1;
                if (o_read) begin
                    if (ctr0 == num_words_m1 || ((op == `OP_ENCODE) && (ctr0_p1 == ctr1)) || (op == `OP_SUM)) begin
                        next_state = ST_IDLE;
                        ctr_all_rst = 1;
                        done_set = 1;
                    end
                    else
                        ctr0_inc = 1;
                end

            end
            else begin
                next_state = ST_IDLE;
                ctr_all_rst = 1;
                done_set = 1;
            end

        end
        ST_TWIDDLE_OUT: begin
                pwm_idx = 1;
                o_valid_int = 1;
                busy = 1;
                o_data = twiddle_ram_dout;
                if (o_read) begin
                    if (ctr0 == num_words_m1) begin
                        next_state = ST_IDLE;
                        ctr_all_rst = 1;
                        done_set = 1;
                        twiddle_out_set = 1;
                    end
                    else
                        ctr0_inc = 1;
                end
        end

    endcase


    // common logic for background BU input/output below

    if (ntt_rcv_bu) begin
        if (sr_o) begin
            if (ctr1 == logn_m1_shft_m1) begin
                ctr1_rst = 1;
            end
            else
                ctr1_inc = 1;
            upoly_ntt = (op == `OP_NTT);
            upoly_intt = (op == `OP_INTT);
            coeff_ram_p0_wsel = ~sr_sel_o;
        end
    end
    else if (pwm_rcv_bu) begin
        if (sr_x && op == `OP_DECOMPRESS) begin
            ctr1_inc = 1;
            upoly_mul = 1;
        end
        else if (sr_o) begin
            ctr1_inc = 1;
            upoly_mul = 1;
            if (op == `OP_DECOMPOSE) begin
                upsi = 1;
            end
        end
    end
    else if (sum_rcv_bu) begin
        if (sr_t) begin
            if (ctr1 == (logn_m1_shft_m1_ctr2)) begin
                ctr1_rst = 1;
            end
            else
                ctr1_inc = 1;
            upoly_mul = 1;
        end
    end
    else if (addsub_rcv_bu) begin
        if (sr_t) begin
            upoly_mul = 1;
            if (ctr1 == n_m1) begin
                // ctr0_rst = 1;
                ctr1_rst = 1;
            end
            else begin
                ctr1_inc = 1;
            end
        end
    end
    else if (encode_rcv_bu) begin
        if (encode_o_valid) begin
            upoly_encode = 1;
            ctr1_inc = 1;
        end
    end


end




always @(*) begin
    case (op)
        `OP_NTT        : next_state_op = ST_NTT0;
        `OP_INTT       : next_state_op = ST_NTT0;
        `OP_PWM        : next_state_op = ST_PWM0;
        `OP_ADD        : next_state_op = ST_ADDSUB;
        `OP_SUB        : next_state_op = ST_ADDSUB;
        `OP_SUM        : next_state_op = ST_SUM0;
        `OP_COMPRESS   : next_state_op = ST_PWM0;
        `OP_DECOMPRESS : next_state_op = ST_PWM0;
        `OP_DECOMPOSE  : next_state_op = ST_PWM0;
        `OP_CHKNORM    : next_state_op = ST_CHKNORM;
        `OP_MAKEHINT   : next_state_op = ST_ADDSUB;
        `OP_ENCODE     : next_state_op = ST_ENCODE0;
        `OP_DECODE     : next_state_op = ST_DECODE;
        default        : next_state_op = ST_IDLE;
    endcase
end


