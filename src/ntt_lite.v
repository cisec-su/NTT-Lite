`include "ntt_lite.vh"

module ntt_lite
   #(   
        parameter LOGN       = 4,
        parameter LOGQ       = 64, // word size, fixed for now
        parameter B          = 32, // bandwidth, must divide LOGQ
        parameter L          = 11, // BU latency
        parameter EN_NTT_OTF = 1,  // enable NTT OTF
        parameter EN_PWM_OTF = 0   // enable PWM OTF
    )
    (
        input              clk,
        input              rst,
        input      [  2:0] cmd,
        input      [  1:0] mode,
        input              otf,
        input      [  3:0] logn,
        input      [  1:0] logq,
        input      [B-1:0] i_data,
        input              i_valid,
        output reg [B-1:0] o_data,
        input              o_read,
        output reg         o_valid,
        output reg         done,
        output reg         busy
    );

localparam N       = 1 << LOGN;
localparam LOGLOGN = $clog2(LOGN); 
localparam LOGWB   = $clog2(LOGQ/B);
localparam WBMASK  = (1 << LOGWB) - 1;

// states, todo: add glitch protection as HW codes
localparam ST_IDLE         = 4'd0;
localparam ST_Q            = 4'd1;
localparam ST_TWIDDLE      = 4'd2;
localparam ST_POLY_IN      = 4'd3;
localparam ST_NTT0         = 4'd4;
localparam ST_NTT1         = 4'd5;
localparam ST_POLY_OUT     = 4'd6;
localparam ST_PWM0         = 4'd7;
localparam ST_PWM1         = 4'd8;
localparam ST_PWM_OTF      = 4'd9;
localparam ST_NTT_OTF      = 4'd10;
localparam ST_TWIDDLE_OTF  = 4'd11;


///////////////////// signal declarations ///////////////////////////////


// data registers
reg [LOGQ-1:0] poly [0:N-1];
reg [LOGQ-1:0] psi  [0:N-1];
reg [LOGQ-1:0] q;
reg [LOGQ-1:0] psi_delta [0:LOGN-1];

// control registers
reg  [3:0]   state;
reg  [LOGN+LOGWB-1:0] ctr0; // general purpose counter 0,
reg  [LOGN+LOGWB-1:0] ctr1; // general purpose counter 1
reg  [LOGN      -1:0] ctr2; // general purpose counter 2
reg  [LOGLOGN   -1:0] ctr3; // counter 3, used for NTT OTF
wire [LOGN      -1:0] maskS; // stage mask

// control signals generated by FSM
reg [3:0] next_state;
reg ctr0_inc, ctr0_rst;
reg ctr1_inc, ctr1_rst;
reg ctr2_inc, ctr2_rst;
reg ctr3_inc, ctr3_rst;
reg [LOGN-1:0] ctr2_d; // general purpose counter 2
reg ctr2_d_set;
reg wpoly, upoly_ntt, upoly_mul, wpsi, wpsi_delta, upsi, wq, pwm_idx;
reg otf_q, otf_set;
reg ntt_rcv_bu, pwm_rcv_bu, pwm_otf_rcv_bu, ntt_otf_rcv_bu, ntt_otf_feed_bu, pwm_otf_feed_bu;
reg ctr_all_rst;
reg set_done, clr_done;

// mode register
reg [1:0] mode_q;
reg mode_set;

// pseudo modes
wire pwm_otf;
wire ntt_otf;

// buttefly inputs
wire [LOGN-1:0] poly_ida;
wire [LOGN-1:0] poly_idb;
wire [LOGN-1:0] psi_idx;

wire [LOGQ-1:0] A_i;
wire [LOGQ-1:0] B_i;
wire [LOGQ-1:0] psi_i;
wire [LOGQ-1:0] A_o;
wire [LOGQ-1:0] B_o;
wire [LOGQ-1:0] M_o;

reg  sr_i;
wire sr_o;

/////////////////////////////////////////////////////////////////////////




///////////////////// BU address generation /////////////////////////////

assign maskS    = (1 << ctr2) - 1; // can be computed sequentially
assign poly_ida = ctr0;
assign poly_idb = (ntt_otf_feed_bu && EN_NTT_OTF) ? ctr3 : (EN_PWM_OTF && pwm_otf_feed_bu) ? (ctr2 + (N/2)) : (pwm_idx) ? ctr0 : (ctr0 + (N/2));
assign psi_idx  = ((EN_PWM_OTF && pwm_otf_feed_bu) || (ntt_otf_feed_bu && EN_NTT_OTF)) ? ctr2 : (pwm_idx) ? ctr0 : (maskS + (ctr0 & maskS));
assign A_i      = poly[poly_ida];
assign B_i      = (ntt_otf_feed_bu && EN_NTT_OTF) ? psi_delta[poly_idb] : (EN_PWM_OTF && pwm_otf_feed_bu) ? psi[poly_idb] : poly[poly_idb];
assign psi_i    = psi[psi_idx];

/////////////////////////////////////////////////////////////////////////




///////////////////// Pseudo Modes //////////////////////////////////////

assign pwm_otf = (EN_PWM_OTF) ? (mode_q == `MODE_PWM) && (otf_q) : 0;
assign ntt_otf = (EN_NTT_OTF) ? (mode_q == `MODE_NTT) && (otf_q) : 0;

/////////////////////////////////////////////////////////////////////////




///////////////////// Sequential Logic //////////////////////////////////


for(genvar i = 0; i < N ;i = i + 1) begin: TWIDDLE_LOAD_GEN
    for(genvar j = 0; j < (LOGQ/B); j = j + 1) begin
        always @(posedge clk) begin
            if (rst) // todo add reset
                psi[i][j*B +: B] <= 0;
            else if (wpsi && (ctr0 == (i*(LOGQ/B) + j)))
                psi[i][j*B +: B] <= i_data;
            else if (upsi && (ctr1 == i))
                psi[i][j*B +: B] <= M_o >> (j*B);
        end
    end
end


if (EN_NTT_OTF) begin
    for(genvar i = 0; i < LOGN ;i = i + 1) begin: TWIDDLE_LOAD_GEN
        for(genvar j = 0; j < (LOGQ/B); j = j + 1) begin
            always @(posedge clk) begin
                if (rst) // todo add reset
                    psi_delta[i][j*B +: B] <= 0;
                else if (wpsi_delta && (ctr0 == (i*(LOGQ/B) + j)))
                    psi_delta[i][j*B +: B] <= i_data;
            end
        end
    end
end

for(genvar i = 0; i < N ;i = i + 1) begin: POLY_GEN
    for(genvar j = 0; j < (LOGQ/B); j = j + 1) begin
        always @(posedge clk) begin
            if (rst)
                poly[i][j*B +: B] <= 0;
            else if (upoly_mul && (ctr1 == i))
                poly[i][j*B +: B] <= M_o >> (j*B);
            else if (upoly_ntt && ((ctr1 << 1) == i))
                poly[i][j*B +: B] <= A_o >> (j*B);
            else if (upoly_ntt && (((ctr1 << 1) + 1) == i))
                poly[i][j*B +: B] <= B_o >> (j*B);
            else if (wpoly && ctr1 == (i*(LOGQ/B) + j))
                poly[i][j*B +: B] <= i_data;
        end
    end
end


for(genvar j = 0; j < (LOGQ/B); j = j + 1) begin
    always @(posedge clk) begin
        if (rst)
            q[j*B +: B] <= 0;
        else if (wq && ctr0 == j)
            q[j*B +: B] <= i_data;
    end
end


always @(posedge clk) begin
    if (rst)
        ctr0 <= 0;
    else if (ctr0_inc)
        ctr0 <= ctr0 + 1;
    else if (ctr0_rst || ctr_all_rst)
        ctr0 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr1 <= 0;
    else if (ctr1_inc)
        ctr1 <= ctr1 + 1;
    else if (ctr1_rst || ctr_all_rst)
        ctr1 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr2 <= 0;
    else if (ctr2_inc)
        ctr2 <= ctr2 + 1;
    else if (ctr2_rst || ctr_all_rst)
        ctr2 <= 0;
end

if (EN_NTT_OTF) begin
    always @(posedge clk) begin
        if (rst)
            ctr3 <= 0;
        else if (ctr3_inc)
            ctr3 <= ctr3 + 1;
        else if (ctr3_rst || ctr_all_rst)
            ctr3 <= 0;
    end
end

always @(posedge clk) begin
    if (rst)
        ctr2_d <= 0;
    else if (ctr2_d_set)
        ctr2_d <= ctr2;
end


always @(posedge clk) begin
    if (rst)
        state <= ST_IDLE;
    else
        state <= next_state;
end


always @(posedge clk) begin
    if (rst)
        mode_q <= 0;
    else if (mode_set)
        mode_q <= mode;
end


always @(posedge clk) begin
    if (rst)
        otf_q <= 0;
    else if (otf_set)
        otf_q <= otf;
end


always @(posedge clk) begin
    if (rst)
        done <= 0;
    else if (set_done)
        done <= 1;
    else if (clr_done)
        done <= 0;
end


/////////////////////////////////////////////////////////////////////////


butterfly btfu
    (
        .clk(clk),
        .rst(rst),
        .CT(1),
        .MT(0),
        .A(A_i),
        .B(B_i),
        .PSI(psi_i),
        .q(q),
        .E(A_o),
        .O(B_o),
        .MUL(M_o)
    );


shiftreg #(.SHIFT(L), .DATA(1)) shreg
    (
        .clk(clk),
        .reset(rst),
        .data_in(sr_i),
        .data_out(sr_o)
    );




///////////////////// FSM ///////////////////////////////////////////////


always @(*) begin

    next_state = state;
    ctr0_inc = 0;
    ctr0_rst = 0;
    ctr1_inc = 0;
    ctr1_rst = 0;
    ctr2_inc = 0;
    ctr2_rst = 0;
    ctr2_d_set = 0;
    ctr3_inc = 0;
    ctr3_rst = 0;
    wpoly = 0;
    upoly_ntt = 0;
    upoly_mul = 0;
    wpsi = 0;
    wpsi_delta = 0;
    upsi = 0;
    wq = 0;
    sr_i = 0;
    busy = 0;
    o_data = {B{1'b0}};
    o_valid = 0;
    mode_set = 0;
    otf_set = 0;
    pwm_idx = 0;
    ntt_rcv_bu = 0;
    pwm_otf_feed_bu = 0;
    ntt_otf_feed_bu = 0;
    pwm_otf_rcv_bu = 0;
    ntt_otf_rcv_bu = 0;
    pwm_rcv_bu = 0;
    ctr_all_rst = 0;
    set_done = 0;
    clr_done = 0;

    case (state)
        ST_IDLE: begin
            clr_done = 1;
            if (cmd == `CMD_LOAD_Q) begin
                next_state = ST_Q;
                if (i_valid) begin
                    ctr0_inc = 1;
                    wq = 1;
                end
            end
            else if (cmd == `CMD_LOAD_TWIDDLE) begin
                next_state = ST_TWIDDLE;
                otf_set = 1;
                if (i_valid) begin
                    ctr0_inc = 1;
                    wpsi = 1;
                end
            end
            else if (cmd == `CMD_LOAD_POLY) begin
                next_state = ST_POLY_IN;
                mode_set = 1;
                otf_set = 1;
                if (i_valid) begin
                    ctr1_inc = 1;
                    wpoly = 1;
                end
            end
            else if (cmd == `CMD_RST) begin
                next_state = ST_IDLE;
                ctr_all_rst = 0;
            end

        end
        ST_Q: begin

            if (i_valid) begin
                wq = 1;
                if (ctr0 == ((LOGQ/B) - 1)) begin
                    next_state = ST_IDLE;
                    ctr0_rst = 1;
                    set_done = 1;
                end
                else
                    ctr0_inc = 1;
            end

        end
        ST_TWIDDLE: begin

            if (i_valid) begin
                wpsi = 1;
                if (ctr0 == (N * (LOGQ/B) - 1)) begin
                    if (EN_NTT_OTF && otf_q) begin
                        next_state = ST_TWIDDLE_OTF;
                    end
                    else begin
                        next_state = ST_IDLE;
                        set_done = 1;
                    end
                    ctr0_rst = 1;
                end
                else
                    ctr0_inc = 1;
            end

        end
        ST_TWIDDLE_OTF: begin

            if (i_valid) begin
                wpsi_delta = 1;
                if (ctr0 == ((LOGN) * (LOGQ/B) - 1)) begin
                    next_state = ST_IDLE;
                    ctr0_rst = 1;
                    set_done = 1;
                end
                else
                    ctr0_inc = 1;
            end

        end
        ST_POLY_IN: begin

            if (i_valid) begin
                wpoly = 1;
                if (pwm_otf && (ctr1 == ((N/2) * (LOGQ/B) - 1))) begin
                    next_state = ST_PWM0;
                    ctr1_rst = 1;
                end
                else if (ctr1 == (N * (LOGQ/B) - 1)) begin
                    next_state = (mode_q == `MODE_NTT) ? ST_NTT0 : (mode_q == `MODE_PWM) ? ST_PWM0 : ST_IDLE;
                    ctr1_rst = 1;
                end
                else
                    ctr1_inc = 1;
            end

        end
        ST_PWM0: begin

            pwm_idx = 1;
            busy = 1;
            sr_i = 1;
            if (((otf_q == 1) && (ctr0 == ((N/2) - 1))) || (ctr0 == (N - 1))) begin
                ctr0_rst = 1;
                next_state = ST_PWM1;
                ctr2_rst = 1;
            end
            else
                ctr0_inc = 1;

            pwm_rcv_bu = 1;

        end
        ST_PWM1: begin

            busy = 1;
            if (((otf_q == 1) && (ctr1 == ((N/2) - 1))) || (ctr1 == (N - 1))) begin
                next_state = ST_POLY_OUT;
            end

            pwm_rcv_bu = 1;

            if (otf_q == 1)begin
                pwm_otf_feed_bu = 1;
            end
        end
        ST_NTT0: begin

            busy = 1;
            sr_i = 1;
            if (ctr0 == ((N/2) - 1)) begin
                ctr0_rst = 1;
                next_state = ST_NTT1;
                ctr2_d_set = 1;
                if (EN_NTT_OTF && ctr2 == (LOGN - 1)) begin
                    ctr2_rst = 1;
                end
            end
            else
                ctr0_inc = 1;

            ntt_rcv_bu = 1;
        end
        ST_NTT1: begin

            busy = 1;
            // BU input for next stage is valid after processing half of the poly
            if ((ctr1 >= (N/4)) && (ctr2_d != (LOGN - 1))) begin
                next_state = ST_NTT0;
                ctr2_inc = 1; // go to next stage
            end
            else if (/*!PRLLOUT && */(ctr1 == ((N/2) - 1))) begin
                next_state = ST_POLY_OUT;
            end

            if (otf_q == 1 && (ctr2_d == (LOGN - 1)))begin
                ntt_otf_feed_bu = 1;
            end
            ntt_rcv_bu = 1;

        end
        ST_POLY_OUT: begin

            o_valid = 1;
            o_data = poly[ctr0 >> LOGWB][(ctr0 & WBMASK) * B +: B];
            busy = 1;
            if (o_read) begin
                if (pwm_otf && (ctr0 == (((N/2) * (LOGQ/B)) - 1))) begin
                    if (ctr1 == (N/2)) begin
                        next_state = ST_IDLE;
                        ctr_all_rst = 1;
                        set_done = 1;
                    end
                    else begin
                        next_state = ST_PWM_OTF;
                    end
                    ctr0_rst = 1;
                end
                else if (ctr0 == ((N * (LOGQ/B)) - 1)) begin
                    if (ntt_otf) begin
                        if (ctr1 == (N - 1)) begin
                            next_state = ST_IDLE;
                            ctr_all_rst = 1;
                            set_done = 1;
                        end
                        else begin
                            next_state = ST_NTT_OTF;
                        end
                        ctr0_rst = 1;
                    end
                    else begin
                        next_state = ST_IDLE;
                        ctr_all_rst = 1;
                        set_done = 1;
                    end
                end
                else
                    ctr0_inc = 1;
            end

            if (ntt_otf) begin
                ntt_otf_feed_bu = 1;
                ntt_otf_rcv_bu = 1;
            end
            else if (pwm_otf) begin
                pwm_otf_feed_bu = 1;
                pwm_otf_rcv_bu = 1;
            end


        end
        ST_PWM_OTF: begin
        // we do not feed the twiddles in this stage. because, it is mathematically guaratneed that all the twiddles are fed for OTF in the ST_POLY_OUT state.
        // note that at least N read will be done, while N/2 twiddles will be fed to BU.
            if (EN_PWM_OTF) begin
                busy = 1;

                if (ctr1 == (N/2)) begin
                    next_state = ST_IDLE;
                    ctr_all_rst = 1;
                    set_done = 1;
                end

                pwm_otf_rcv_bu = 1;
            end
        end
        ST_NTT_OTF: begin
        // we do not feed the twiddles in this stage. because, it is mathematically guaratneed that all the twiddles are fed for OTF in the ST_POLY_OUT state.
        // note that at least N read will be done, while N/2 twiddles will be fed to BU.
            if (EN_NTT_OTF) begin
                busy = 1;

                if (ctr1 == (N - 1)) begin
                    next_state = ST_IDLE;
                    ctr_all_rst = 1;
                    set_done = 1;
                end

                ntt_otf_rcv_bu = 1;
            end
        end

    endcase


    // common logic for background BU input/output below

    if (EN_NTT_OTF && ntt_otf_feed_bu) begin
        if (ctr2 <= (N - 2)) begin
            ctr2_inc = 1;
            sr_i = 1;
        end
        if (((ctr2 + 2) >> (ctr3 + 1)) & 1'b1) begin
            ctr3_inc = 1;
        end
    end
    else if (EN_PWM_OTF && pwm_otf_feed_bu) begin
        if (ctr2 <= ((N/2) - 1)) begin
            ctr2_inc = 1;
            sr_i = 1;
        end
    end

    if (ntt_rcv_bu) begin
        if (sr_o) begin
            if (ctr1 == ((N/2) - 1)) begin
                ctr1_rst = 1;
            end
            else
                ctr1_inc = 1;
            upoly_ntt = 1;
        end
    end
    else if (pwm_rcv_bu) begin
        if (sr_o) begin
            if (EN_PWM_OTF && otf_q == 1 && (ctr1 == ((N/2) - 1))) begin
                ctr1_rst = 1;
            end
            else
                ctr1_inc = 1;
            upoly_mul = 1;
        end
    end
    else if (EN_NTT_OTF && ntt_otf_rcv_bu) begin
        if (sr_o) begin
            upsi = 1;
            if (ctr1 <= (N - 2)) begin
                ctr1_inc = 1;
            end
        end
    end
    else if (EN_PWM_OTF && pwm_otf_rcv_bu) begin
        if (sr_o) begin
            upsi = 1;
            if (ctr1 <= ((N/2) - 1)) begin
                ctr1_inc = 1;
            end
        end
    end


end

