///////////////////// Sequential Logic //////////////////////////////////


always @(posedge clk) begin
    if (rst)
        ctr0 <= 0;
    else if (ctr0_inc)
        ctr0 <= ctr0_p1;
    else if (ctr0_rst || ctr_all_rst)
        ctr0 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr1 <= 0;
    else if (ctr1_inc)
        ctr1 <= ctr1 + 1;
    else if (ctr1_rst || ctr_all_rst)
        ctr1 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr2 <= 0;
    else if (ctr2_inc)
        ctr2 <= ctr2 + 1;
    else if (ctr2_rst || ctr_all_rst)
        ctr2 <= 0;
end


always @(posedge clk) begin
    ctr0_d <= ctr0;
end


always @(posedge clk) begin
    if (rst)
        ctr2_d <= 0;
    else if (ctr2_d_set) //todo: check if needed
        ctr2_d <= ctr2;
end


always @(posedge clk) begin
    if (rst)
        state <= ST_IDLE;
    else
        state <= next_state;
end


always @(posedge clk) begin
    if (rst)
        {done, done_int} <= 0;
    else if (done_set)
        {done, done_int} <= 2'b01;
    else if (done_int)
        {done, done_int} <= 2'b10;
    else if (done)
        {done, done_int} <= 2'b00;
end


always @(posedge clk) begin
    if (rst)
        error <= 0;
    else if (error_set)
        error <= 1;
    else if (error)
        error <= 0;
end


always @(posedge clk) begin
    if (rst)
        o_valid <= 0;
    else
        o_valid <= o_valid_int;
end


always @(posedge clk) begin
    if (rst)
        twiddle_out_q <= 0;
    else if (twiddle_out_set)
        twiddle_out_q <= 1;
    else if (twiddle_out_q)
        twiddle_out_q <= 0;
end


always @(posedge clk) begin
    if (rst)
        {chknorm, chknorm_int} <= 0;
    else if (chknorm_set)
        {chknorm, chknorm_int} <= 2'b01;
    else if (chknorm_int)
        {chknorm, chknorm_int} <= 2'b10;
    else if (chknorm)
        {chknorm, chknorm_int} <= 2'b00;
end


always @(posedge clk) begin
    i_data_q <= i_data;
end

always @(posedge clk) begin
    poly_in_frwrd_A_q <= poly_in_frwrd_A;
end

always @(posedge clk) begin
    poly_in_frwrd_B_q <= poly_in_frwrd_B;
end

always @(posedge clk) begin
    twiddle_frwrd_q <= twiddle_frwrd;
end

always @(posedge clk) begin
    upoly_ntt_q <= upoly_ntt;
end

always @(posedge clk) begin
    B_o_q <= B_o;
end

always @(posedge clk) begin
    ntt_waddr_q <= ntt_waddr;
end

