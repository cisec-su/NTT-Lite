`include "ntt_lite.vh"

module ntt_lite
   #(   
        parameter LOGN       = 8,
        parameter LOGQ       = 32,
        parameter B          = 32, // bandwidth, must divide LOGQ
        parameter L_RED      = 5, // BU  latency
        parameter L_MUL      = 3, // MUL latency
        parameter EN_NTT_OTF = 0
    )
    (
        input                       clk      ,
        input                       rst      ,
        input      [           3:0] cmd      ,
        input      [           3:0] op       ,
        input                       otf      ,
        input      [   LOGLOGN-1:0] logn     ,
        input      [   LOGLOGQ-1:0] k        ,
        input      [   LOGLOGQ-1:0] d        ,        
        input      [      LOGQ-1:0] q        ,
        input      [      LOGQ-1:0] inv2     ,
        input      [      LOGQ-1:0] bound    ,
        input      [    LOGQ*2-1:0] mu       ,
        input      [           1:0] mode     ,
        input      [         B-1:0] i_data   ,
        output reg                  i_ready  ,
        input                       op_switch,
        input                       rhs_const,
        input                       i_valid  ,
        input                       o_dis    ,
        input                       floor    ,
        output reg [         B-1:0] o_data   ,
        input                       o_read   ,
        output reg                  chknorm  ,
        output reg                  o_valid  ,
        output reg [LOGN+LOGWB-1:0] io_word  ,
        output reg                  done     ,
        output reg                  busy     ,
        output reg                  error
   );

///////////////////// input checks //////////////////////////////////////

if (LOGQ != B) begin
    LOGQ_MUST_BE_EQUAL_TO_B();
end

/////////////////////////////////////////////////////////////////////////




///////////////////// local parameters //////////////////////////////////

localparam LOGLOGQ = $rtoi($ceil($clog2(LOGQ + 1)));
localparam N       = 1 << LOGN;
localparam LOGLOGN = $rtoi($ceil($clog2(LOGN+1))); 
localparam LOGWB   = $clog2(LOGQ/B);
localparam WBMASK  = (1 << LOGWB) - 1;
localparam L       = L_MUL + L_RED;

// states, todo: add glitch protection as HW codes
localparam ST_IDLE         = 5'd0;
localparam ST_TWIDDLE_IN   = 5'd2;
localparam ST_POLY_IN      = 5'd3;
localparam ST_NTT0         = 5'd4;
localparam ST_NTT1         = 5'd5;
localparam ST_POLY_OUT     = 5'd6;
localparam ST_PWM0         = 5'd7;
localparam ST_PWM1         = 5'd8;
localparam ST_ADDSUB       = 5'd12;
localparam ST_ENCODE0      = 5'd13;
localparam ST_ENCODE1      = 5'd14;
localparam ST_DECODE       = 5'd15;
localparam ST_SUM0         = 5'd16;
localparam ST_SUM1         = 5'd17;
localparam ST_TWIDDLE_OUT  = 5'd18;
localparam ST_CHKNORM      = 5'd19;
// localparam ST_POLY_FORWARD = 5'd20;
localparam ST_POLY_FORWARD_PWM    = 5'd21;
localparam ST_POLY_FORWARD_ADDSUB = 5'd22;
localparam ST_POLY_FORWARD_NTT    = 5'd23;
localparam ST_POLY_FORWARD_ENCODE = 5'd24;
localparam ST_TWIDDLE_FORWARD_ADDSUB = 5'd25;
localparam ST_TWIDDLE_FORWARD_PWM    = 5'd26;



/////////////////////////////////////////////////////////////////////////




///////////////////// signal declarations ///////////////////////////////

// data registers
reg [LOGQ-1:0] psi_delta [0:LOGN-1];

// control registers
reg  [4:0]   state;
reg  [LOGN+LOGWB-1:0] ctr0; // general purpose counter 0,
reg  [LOGN+LOGWB-1:0] ctr1; // general purpose counter 1
reg  [LOGN      -1:0] ctr2; // general purpose counter 2
reg  [LOGLOGN   -1:0] ctr3; // counter 3, used for NTT OTF
wire [LOGN      -1:0] maskS; // stage mask
wire [LOGN      -1:0] maskIS; // stage inv. mask

// control signals generated by FSM
reg [4:0] next_state;
reg [4:0] next_state_op;
reg ctr0_inc, ctr0_rst;
reg ctr1_inc, ctr1_rst;
reg ctr2_inc, ctr2_rst;
reg ctr3_inc, ctr3_rst;
reg [LOGN+LOGWB-1:0] ctr0_d;
wire [LOGN+LOGWB :0] ctr0_p1;
reg [LOGN-1:0] ctr2_d;
reg ctr2_d_set;
reg wpoly, upoly_ntt, upoly_intt, upoly_mul, wpsi, wpsi_delta, upsi, wq, pwm_idx, upoly_encode;
reg ntt_rcv_bu, pwm_rcv_bu, sum_rcv_bu, addsub_rcv_bu, encode_rcv_bu;
reg ctr_all_rst;
reg done_set, done_int;
reg o_valid_int;

reg twiddle_out_q, twiddle_out_set;

// logn register
wire [LOGN  :0] n;
wire [LOGN-1:0] n_m1;
wire [LOGN-1:0] n_m2;
wire [LOGLOGN-1:0] logn_m1;
wire [LOGN   -1:0] n_over2;
wire [LOGN   -2:0] n_over4;
wire [LOGN   -1:0] logn_m1_shft_m1;
wire [LOGN   -1:0] logn_m1_shft_m1_ctr2;
wire [LOGN+LOGWB  :0] num_words;
wire [LOGN+LOGWB-1:0] num_words_m1;
wire [LOGN+LOGWB-1:0] num_words_over2;
wire [LOGN+LOGWB-1:0] num_words_over2_m1;


// error register
reg error_set;


// buttefly inputs
wire [LOGQ-1:0] A_i;
wire [LOGQ-1:0] B_i;
wire [LOGQ-1:0] psi_i;
wire [LOGQ-1:0] A_o;
wire [LOGQ-1:0] B_o;
wire [LOGQ-1:0] M_o;

// chk norm
wire chknorm_bu;
reg chknorm_int, chknorm_set;

reg  sr_i;
wire sr_o;
wire sr_t;
wire sr_z;
wire sr_x;
wire sr_sel_i;
wire sr_sel_o;


// bram signals
wire coeff_ram_p0_wen;
wire [LOGN-1:0] coeff_ram_p0_waddr;
wire [LOGQ-1:0] coeff_ram_p0_din;
wire [LOGN-1:0] coeff_ram_p0_raddr;
wire [LOGQ-1:0] coeff_ram_p0_dout;
wire coeff_ram_p1_wen;
wire [LOGN-1:0] coeff_ram_p1_waddr;
wire [LOGQ-1:0] coeff_ram_p1_din;
wire [LOGN-1:0] coeff_ram_p1_raddr;
wire [LOGQ-1:0] coeff_ram_p1_dout;
wire twiddle_ram_wen;
wire [LOGN-1:0] twiddle_ram_waddr;
wire [LOGQ-1:0] twiddle_ram_din;
wire [LOGN-1:0] twiddle_ram_raddr;
wire [LOGQ-1:0] twiddle_ram_dout;

reg  coeff_ram_p0_rsel;
wire coeff_ram_p1_rsel;
reg  coeff_ram_p0_wsel;
wire coeff_ram_p1_wsel;

// encode signals
wire [LOGQ-1:0] encode_in;
wire [LOGQ-1:0] encode_out;
wire decode;
reg  encode_rst;
wire encode_i_valid;
wire encode_i_ready;
wire encode_o_valid;


// parallel input and point-op
reg [B-1:0] i_data_q;
reg poly_in_frwrd_A, poly_in_frwrd_A_q;
reg poly_in_frwrd_B, poly_in_frwrd_B_q;
reg twiddle_frwrd  , twiddle_frwrd_q;
wire [LOGQ-1:0] poly_in_mx_A;
wire [LOGQ-1:0] poly_in_mx_B;
wire [LOGQ-1:0] twiddle_in_mx;

/////////////////////////////////////////////////////////////////////////




///////////////////// Comb. Logic for N/LOGN/LOGLOGN ////////////////////

assign n = 1 << logn;
assign n_m1 = n - 1;
assign n_m2 = n - 2;
assign logn_m1 = logn - 1;
assign n_over2 = 1 << logn_m1;
assign n_over4 = n_over2 >> 1;
assign logn_m1_shft_m1 = n_over2 - 1;
assign logn_m1_shft_m1_ctr2 = logn_m1_shft_m1 >> ctr2;
assign num_words = ((LOGQ/B) << logn);
assign num_words_m1 = num_words - 1;
assign num_words_over2 = num_words >> 1;
assign num_words_over2_m1 = num_words_over2 - 1;
assign ctr0_p1 = ctr0 + 1;

/////////////////////////////////////////////////////////////////////////




///////////////////// BU inputs /////////////////////////////////////////

assign poly_in_mx_A = (poly_in_frwrd_A_q) ? i_data_q : coeff_ram_p0_dout;
assign poly_in_mx_B = (poly_in_frwrd_B_q) ? i_data_q : coeff_ram_p1_dout;
assign twiddle_in_mx = (rhs_const) ? bound : (twiddle_frwrd_q) ? i_data_q : twiddle_ram_dout;

assign A_i      = (op_switch) ? twiddle_in_mx  : poly_in_mx_A;
assign B_i      = poly_in_mx_B;
assign psi_i    = (op_switch) ? poly_in_mx_A : twiddle_in_mx;

/////////////////////////////////////////////////////////////////////////




///////////////////// bram signals //////////////////////////////////////

assign sr_sel_i = coeff_ram_p0_rsel;
assign coeff_ram_p1_rsel = coeff_ram_p0_rsel;
assign coeff_ram_p1_wsel = coeff_ram_p0_wsel;

assign coeff_ram_p0_wen   =  wpoly | upoly_mul | upoly_ntt | upoly_intt | upoly_encode;
assign coeff_ram_p0_waddr = (wpoly        ) ?   ctr1       : 
                            (upoly_mul    ) ?   ctr1       : 
                            (upoly_encode ) ?   ctr1       : 
                            (upoly_ntt    ) ?  (ctr1 << 1) : 
                          /*(upoly_intt) ?*/ ctr1 /*   : 0*/;
assign coeff_ram_p0_din   = (wpoly                   ) ?   i_data      : 
                            (upoly_mul               ) ?   M_o         : 
                            (upoly_encode            ) ?   encode_out  : 
                          /*(upoly_ntt | upoly_intt  ) ?*/ A_o  /*: 0*/;
assign coeff_ram_p0_raddr = ((op == `OP_INTT || op == `OP_SUM) && !pwm_idx) ? (ctr0 << 1)  : 
                                                                               ctr0        ;

assign coeff_ram_p1_wen   =  upoly_ntt | upoly_intt;
assign coeff_ram_p1_waddr = (upoly_ntt ) ?  (ctr1 << 1) + 1   : 
                          /*(upoly_intt) ?*/ ctr1 + n_over2 /*: 0*/;
assign coeff_ram_p1_din   =  B_o;
assign coeff_ram_p1_raddr = (pwm_idx                        ) ?  ctr0             : 
                            (op == `OP_INTT || op == `OP_SUM) ? ((ctr0 << 1) + 1) :  
                                                                (ctr0 + n_over2)  ;
// todo: check pwm_idx, use `OP_PWM if posslbe

assign maskS    = (1 << ctr2) - 1 ;
assign maskIS   = ((1 << (logn_m1 - ctr2)) - 1);

assign twiddle_ram_wen   =  wpsi | upsi;
assign twiddle_ram_waddr = (wpsi) ? ctr0 : /*(upsi) ?*/ ctr1/* : 0*/;
assign twiddle_ram_din   = (wpsi) ? i_data : /*(upsi) ?*/ A_o/* : 0*/;
assign twiddle_ram_raddr = (pwm_idx                      ) ?                    ctr0            : 
                           (op == `OP_INTT               ) ? (  maskIS       + (ctr0 & maskIS)) : 
                                                             (  maskS        + (ctr0 & maskS )) ; 

/////////////////////////////////////////////////////////////////////////





///////////////////// Encode Inputs /////////////////////////////////////

assign encode_i_valid = sr_t; // TODO: check if we should filter out based on the opcode or not.
assign encode_in      = (decode) ? twiddle_ram_dout  :
                                   poly_in_mx_A      ;
assign decode         = (op == `OP_DECODE) ? 1'b1 : 
                                             1'b0 ;

/////////////////////////////////////////////////////////////////////////



///////////////////// Sequential Logic //////////////////////////////////


always @(posedge clk) begin
    if (rst)
        ctr0 <= 0;
    else if (ctr0_inc)
        ctr0 <= ctr0_p1;
    else if (ctr0_rst || ctr_all_rst)
        ctr0 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr1 <= 0;
    else if (ctr1_inc)
        ctr1 <= ctr1 + 1;
    else if (ctr1_rst || ctr_all_rst)
        ctr1 <= 0;
end


always @(posedge clk) begin
    if (rst)
        ctr2 <= 0;
    else if (ctr2_inc)
        ctr2 <= ctr2 + 1;
    else if (ctr2_rst || ctr_all_rst)
        ctr2 <= 0;
end


always @(posedge clk) begin
    ctr0_d <= ctr0;
end


always @(posedge clk) begin
    if (rst)
        ctr2_d <= 0;
    else if (ctr2_d_set) //todo: check if needed
        ctr2_d <= ctr2;
end


always @(posedge clk) begin
    if (rst)
        state <= ST_IDLE;
    else
        state <= next_state;
end


always @(posedge clk) begin
    if (rst)
        {done, done_int} <= 0;
    else if (done_set)
        {done, done_int} <= 2'b01;
    else if (done_int)
        {done, done_int} <= 2'b10;
    else if (done)
        {done, done_int} <= 2'b00;
end


always @(posedge clk) begin
    if (rst)
        error <= 0;
    else if (error_set)
        error <= 1;
    else if (error)
        error <= 0;
end


always @(posedge clk) begin
    if (rst)
        o_valid <= 0;
    else
        o_valid <= o_valid_int;
end


always @(posedge clk) begin
    if (rst)
        twiddle_out_q <= 0;
    else if (twiddle_out_set)
        twiddle_out_q <= 1;
    else if (twiddle_out_q)
        twiddle_out_q <= 0;
end


always @(posedge clk) begin
    if (rst)
        {chknorm, chknorm_int} <= 0;
    else if (chknorm_set)
        {chknorm, chknorm_int} <= 2'b01;
    else if (chknorm_int)
        {chknorm, chknorm_int} <= 2'b10;
    else if (chknorm)
        {chknorm, chknorm_int} <= 2'b00;
end


always @(posedge clk) begin
    i_data_q <= i_data;
end

always @(posedge clk) begin
    poly_in_frwrd_A_q <= poly_in_frwrd_A;
end

always @(posedge clk) begin
    poly_in_frwrd_B_q <= poly_in_frwrd_B;
end

always @(posedge clk) begin
    twiddle_frwrd_q <= twiddle_frwrd;
end


